-- Arbitrage AI paper-only worker schema.
-- The worker uses the Supabase service role key server-side; never expose it in Streamlit/browser code.

create table if not exists public.arb_scans (
    id bigint generated by default as identity primary key,
    run_id bigint,
    scanned_at timestamptz not null default now(),
    status text not null default 'ok',
    opportunities jsonb not null default '[]'::jsonb,
    errors jsonb not null default '[]'::jsonb,
    diagnostics jsonb not null default '{}'::jsonb,
    real_orders_enabled boolean not null default false
);

alter table public.arb_scans add column if not exists run_id bigint;
alter table public.arb_scans add column if not exists scanned_at timestamptz not null default now();
alter table public.arb_scans add column if not exists status text not null default 'ok';
alter table public.arb_scans add column if not exists opportunities jsonb not null default '[]'::jsonb;
alter table public.arb_scans add column if not exists errors jsonb not null default '[]'::jsonb;
alter table public.arb_scans add column if not exists diagnostics jsonb not null default '{}'::jsonb;
alter table public.arb_scans add column if not exists real_orders_enabled boolean not null default false;

create table if not exists public.arb_state (
    state_key text primary key,
    payload jsonb not null default '{}'::jsonb,
    updated_at timestamptz not null default now()
);

alter table public.arb_state add column if not exists payload jsonb not null default '{}'::jsonb;
alter table public.arb_state add column if not exists updated_at timestamptz not null default now();

create table if not exists public.arb_validations (
    id bigint generated by default as identity primary key,
    route_id text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz,
    entry jsonb not null,
    initial_opportunity jsonb not null default '{}'::jsonb,
    results jsonb not null default '{}'::jsonb,
    done boolean not null default false,
    real_order_placed boolean not null default false
);

alter table public.arb_validations add column if not exists route_id text;
alter table public.arb_validations add column if not exists created_at timestamptz not null default now();
alter table public.arb_validations add column if not exists updated_at timestamptz;
alter table public.arb_validations add column if not exists entry jsonb not null default '{}'::jsonb;
alter table public.arb_validations add column if not exists initial_opportunity jsonb not null default '{}'::jsonb;
alter table public.arb_validations add column if not exists results jsonb not null default '{}'::jsonb;
alter table public.arb_validations add column if not exists done boolean not null default false;
alter table public.arb_validations add column if not exists real_order_placed boolean not null default false;

create index if not exists arb_scans_scanned_at_idx on public.arb_scans (scanned_at desc);
create index if not exists arb_validations_pending_idx on public.arb_validations (done, created_at);
create index if not exists arb_validations_route_created_idx on public.arb_validations (route_id, created_at desc);

alter table public.arb_scans enable row level security;
alter table public.arb_state enable row level security;
alter table public.arb_validations enable row level security;

revoke all on public.arb_scans from anon, authenticated;
revoke all on public.arb_state from anon, authenticated;
revoke all on public.arb_validations from anon, authenticated;

grant select on public.arb_scans to anon, authenticated;
grant select on public.arb_validations to anon, authenticated;
grant all on public.arb_scans to service_role;
grant all on public.arb_state to service_role;
grant all on public.arb_validations to service_role;

drop policy if exists "dashboard_read_scans" on public.arb_scans;
create policy "dashboard_read_scans" on public.arb_scans
    for select to anon, authenticated using (true);

drop policy if exists "dashboard_read_validations" on public.arb_validations;
create policy "dashboard_read_validations" on public.arb_validations
    for select to anon, authenticated using (true);

-- No anon/authenticated policy is created for arb_state.
